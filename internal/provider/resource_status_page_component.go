var (
	_ resource.Resource                = (*statusPageComponentResource)(nil)
	_ resource.ResourceWithImportState = (*statusPageComponentResource)(nil)
)

func NewStatusPageComponentResource() resource.Resource { return &statusPageComponentResource{} }

type statusPageComponentResource struct{ baseResource }

type statusPageComponentModel struct {
	ID          types.String `tfsdk:"id"`
	Key         types.String `tfsdk:"key"`
	Statuspage  types.String `tfsdk:"statuspage"`
	Monitor     types.String `tfsdk:"monitor"`
	Group       types.String `tfsdk:"group"`
	Name        types.String `tfsdk:"name"`
	Description types.String `tfsdk:"description"`
	Autopublish types.Bool   `tfsdk:"autopublish"`
	Position    types.String `tfsdk:"position"`
	Type        types.String `tfsdk:"type"`
}

func (r *statusPageComponentResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_status_page_component"
}

func (r *statusPageComponentResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	keep := stringplanmodifier.UseStateForUnknown()
	replace := stringplanmodifier.RequiresReplace()
	resp.Schema = schema.Schema{
		Description: "Shows a monitor or a group on a status page.",
		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				Description:   "Same as key.",
				Computed:      true,
				PlanModifiers: []planmodifier.String{keep},
			},
			"key": schema.StringAttribute{
				Description:   "Unique identifier generated by Cronitor.",
				Computed:      true,
				PlanModifiers: []planmodifier.String{keep},
			},
			"statuspage": schema.StringAttribute{
				Description:   "Key of the status page.",
				Required:      true,
				PlanModifiers: []planmodifier.String{replace},
			},
			"monitor": schema.StringAttribute{
				Description:   "Key of the monitor to show. Exactly one of monitor or group is required.",
				Optional:      true,
				PlanModifiers: []planmodifier.String{replace},
				Validators: []validator.String{
					stringvalidator.ExactlyOneOf(path.MatchRoot("monitor"), path.MatchRoot("group")),
				},
			},
			"group": schema.StringAttribute{
				Description:   "Key of the group to show. Exactly one of monitor or group is required.",
				Optional:      true,
				PlanModifiers: []planmodifier.String{replace},
			},
			"name": schema.StringAttribute{
				Description:   "Display name. Defaults to the monitor or group name.",
				Optional:      true,
				Computed:      true,
				PlanModifiers: []planmodifier.String{keep},
				Validators:    []validator.String{stringvalidator.LengthBetween(1, 128)},
			},
			"description": schema.StringAttribute{
				Description: "Description text.",
				Optional:    true,
				Validators:  []validator.String{stringvalidator.LengthBetween(1, 2048)},
			},
			"autopublish": schema.BoolAttribute{
				Description:   "Automatically publish incidents for this component.",
				Optional:      true,
				Computed:      true,
				PlanModifiers: []planmodifier.Bool{boolplanmodifier.UseStateForUnknown()},
			},
			"position": schema.StringAttribute{
				Description:   "Sort position of the component on the page.",
				Optional:      true,
				Computed:      true,
				PlanModifiers: []planmodifier.String{keep},
				Validators:    []validator.String{stringvalidator.LengthBetween(1, 64)},
			},
			"type": schema.StringAttribute{
				Description:   "Component type: job, check, heartbeat, event or group.",
				Computed:      true,
				PlanModifiers: []planmodifier.String{keep},
			},
		},
	}
}

func (m *statusPageComponentModel) toInput(update bool) client.StatusPageComponentInput {
	in := client.StatusPageComponentInput{"statuspage": m.Statuspage.ValueString()}
	if !update {
		if known(m.Monitor) {
			in["monitor"] = m.Monitor.ValueString()
		}
		if known(m.Group) {
			in["group"] = m.Group.ValueString()
		}
	}
	if known(m.Description) || update {
		in["description"] = nullableString(m.Description)
	}
	if known(m.Name) {
		in["name"] = m.Name.ValueString()
	}
	if known(m.Position) {
		in["position"] = m.Position.ValueString()
	}
	if known(m.Autopublish) {
		in["autopublish"] = m.Autopublish.ValueBool()
	}
	return in
}

func (m *statusPageComponentModel) fromAPI(api *client.StatusPageComponent) {
	m.ID = types.StringValue(api.Key)
	m.Key = types.StringValue(api.Key)
	// The component's targets cannot change after creation, and the API may
	// identify them differently than configured, so only fill them when unset
	// (e.g. on import).
	if !known(m.Statuspage) {
		m.Statuspage = stringOrNull(string(api.Statuspage))
	}
	if !known(m.Monitor) && !known(m.Group) {
		m.Monitor = stringOrNull(string(api.Monitor))
		m.Group = stringOrNull(string(api.Group))
	}
	m.Name = stringOrNull(api.Name)
	m.Description = stringPtrOrNull(api.Description)
	m.Autopublish = types.BoolValue(api.Autopublish)
	m.Position = stringOrNull(string(api.Position))
	m.Type = stringOrNull(api.Type)
}

func (r *statusPageComponentResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan statusPageComponentModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	api, err := r.client.CreateStatusPageComponent(ctx, plan.toInput(false))
	if err != nil {
		resp.Diagnostics.AddError("Error creating status page component", err.Error())
		return
	}
	plan.fromAPI(api)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *statusPageComponentResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state statusPageComponentModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	api, err := r.client.GetStatusPageComponent(ctx, state.Key.ValueString())
	if client.IsNotFound(err) {
		resp.State.RemoveResource(ctx)
		return
	}
	if err != nil {
		resp.Diagnostics.AddError("Error reading status page component", err.Error())
		return
	}
	state.fromAPI(api)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *statusPageComponentResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan statusPageComponentModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	api, err := r.client.UpdateStatusPageComponent(ctx, plan.Key.ValueString(), plan.toInput(true))
	if err != nil {
		resp.Diagnostics.AddError("Error updating status page component", err.Error())
		return
	}
	plan.fromAPI(api)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *statusPageComponentResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state statusPageComponentModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.client.DeleteStatusPageComponent(ctx, state.Key.ValueString()); err != nil && !client.IsNotFound(err) {
		resp.Diagnostics.AddError("Error deleting status page component", err.Error())
	}
}

func (r *statusPageComponentResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("key"), req, resp)
}
