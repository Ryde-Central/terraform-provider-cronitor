func NewMaintenanceWindowResource() resource.Resource { return &maintenanceWindowResource{} }

type maintenanceWindowResource struct{ baseResource }

type maintenanceWindowModel struct {
	ID                          types.String `tfsdk:"id"`
	Key                         types.String `tfsdk:"key"`
	Name                        types.String `tfsdk:"name"`
	Description                 types.String `tfsdk:"description"`
	Start                       types.String `tfsdk:"start"`
	End                         types.String `tfsdk:"end"`
	AffectsAllMonitors          types.Bool   `tfsdk:"affects_all_monitors"`
	AffectsStatuspageComponents types.Bool   `tfsdk:"affects_statuspage_components"`
	Environment                 types.String `tfsdk:"environment"`
	Monitors                    types.Set    `tfsdk:"monitors"`
	Groups                      types.Set    `tfsdk:"groups"`
	Statuspages                 types.Set    `tfsdk:"statuspages"`
	Duration                    types.Int64  `tfsdk:"duration"`
	State                       types.String `tfsdk:"state"`
}

// rfc3339Validator checks that a string is an RFC 3339 timestamp.
type rfc3339Validator struct{}

func (rfc3339Validator) Description(context.Context) string {
	return "value must be an RFC 3339 timestamp, e.g. 2026-01-02T03:00:00Z"
}

func (v rfc3339Validator) MarkdownDescription(ctx context.Context) string { return v.Description(ctx) }

func (v rfc3339Validator) ValidateString(ctx context.Context, req validator.StringRequest, resp *validator.StringResponse) {
	if !known(req.ConfigValue) {
		return
	}
	if _, err := time.Parse(time.RFC3339, req.ConfigValue.ValueString()); err != nil {
		resp.Diagnostics.AddAttributeError(req.Path, "Invalid timestamp", fmt.Sprintf("%s: %s", v.Description(ctx), err))
	}
}

func (r *maintenanceWindowResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_maintenance_window"
}

