var (
	_ resource.Resource                   = (*statusPageResource)(nil)
	_ resource.ResourceWithImportState    = (*statusPageResource)(nil)
	_ resource.ResourceWithValidateConfig = (*statusPageResource)(nil)
)

func NewStatusPageResource() resource.Resource { return &statusPageResource{} }

type statusPageResource struct{ baseResource }

type statusPageModel struct {
	ID                       types.String `tfsdk:"id"`
	Key                      types.String `tfsdk:"key"`
	Name                     types.String `tfsdk:"name"`
	HostedSubdomain          types.String `tfsdk:"hosted_subdomain"`
	CustomDomain             types.String `tfsdk:"custom_domain"`
	LogoURL                  types.String `tfsdk:"logo_url"`
	WebsiteURL               types.String `tfsdk:"website_url"`
	SupportURL               types.String `tfsdk:"support_url"`
	AllowSearchIndex         types.Bool   `tfsdk:"allow_search_index"`
	EnablePerformanceMetrics types.Bool   `tfsdk:"enable_performance_metrics"`
	EnableDarkMode           types.Bool   `tfsdk:"enable_dark_mode"`
	DefaultTimePeriod        types.String `tfsdk:"default_time_period"`
	Access                   types.String `tfsdk:"access"`
	Password                 types.String `tfsdk:"password"`
	IPAllowlist              types.String `tfsdk:"ip_allowlist"`
	Environment              types.String `tfsdk:"environment"`
	BadgeURLLight            types.String `tfsdk:"badge_url_light"`
	BadgeURLDark             types.String `tfsdk:"badge_url_dark"`
	Created                  types.String `tfsdk:"created"`
}

func (r *statusPageResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_status_page"
}

func (r *statusPageResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	keep := stringplanmodifier.UseStateForUnknown()
	keepBool := boolplanmodifier.UseStateForUnknown()
	optionalString := func(desc string) schema.StringAttribute {
		return schema.StringAttribute{
			Description: desc,
			Optional:    true,
			Validators:  []validator.String{stringvalidator.LengthAtLeast(1)},
		}
	}
	computedBool := func(desc string) schema.BoolAttribute {
		return schema.BoolAttribute{
			Description:   desc,
			Optional:      true,
			Computed:      true,
			PlanModifiers: []planmodifier.Bool{keepBool},
		}
	}
	computedString := func(desc string) schema.StringAttribute {
		return schema.StringAttribute{
			Description:   desc,
			Computed:      true,
			PlanModifiers: []planmodifier.String{keep},
		}
	}

	resp.Schema = schema.Schema{
		Description: "A hosted status page. Add monitors or groups to it with cronitor_status_page_component.",
		Attributes: map[string]schema.Attribute{
			"id":  computedString("Same as key."),
			"key": computedString("Unique identifier generated by Cronitor."),
			"name": schema.StringAttribute{
				Description: "Display name.",
				Required:    true,
				Validators:  []validator.String{stringvalidator.LengthBetween(1, 100)},
			},
			"hosted_subdomain": schema.StringAttribute{
				Description: "Subdomain of the hosted page, i.e. <hosted_subdomain>.cronitorstatus.com.",
				Required:    true,
				Validators:  []validator.String{stringvalidator.LengthBetween(1, 63)},
			},
			"custom_domain":              optionalString("Custom domain for the page. Requires DNS configuration."),
			"logo_url":                   optionalString("URL of a logo image."),
			"website_url":                optionalString("URL of your main website."),
			"support_url":                optionalString("URL of your support page."),
			"allow_search_index":         computedBool("Allow search engines to index the page."),
			"enable_performance_metrics": computedBool("Show performance metrics on the page."),
			"enable_dark_mode":           computedBool("Enable dark mode."),
			"default_time_period": schema.StringAttribute{
				Description:   "Default time period shown: 24h, 7d, 30d or 90d.",
				Optional:      true,
				Computed:      true,
				PlanModifiers: []planmodifier.String{keep},
				Validators:    []validator.String{stringvalidator.OneOf("24h", "7d", "30d", "90d")},
			},
			"access": schema.StringAttribute{
				Description:   "public or password. A password page also needs password.",
				Optional:      true,
				Computed:      true,
				PlanModifiers: []planmodifier.String{keep},
				Validators:    []validator.String{stringvalidator.OneOf("public", "password")},
			},
			"password": schema.StringAttribute{
				Description: "Password for pages with access = \"password\". Write-only in the API, so changes made outside Terraform are not detected.",
				Optional:    true,
				Sensitive:   true,
				Validators:  []validator.String{stringvalidator.LengthAtLeast(1)},
			},
			"ip_allowlist": optionalString("IP addresses or CIDR ranges allowed to view the page."),
			"environment": schema.StringAttribute{
				Description:   "Key of the environment whose monitor status the page shows.",
				Optional:      true,
				Computed:      true,
				PlanModifiers: []planmodifier.String{keep},
			},
			"badge_url_light": computedString("URL of the light status badge."),
			"badge_url_dark":  computedString("URL of the dark status badge."),
			"created":         computedString("When the page was created."),
		},
	}
}

func (r *statusPageResource) ValidateConfig(ctx context.Context, req resource.ValidateConfigRequest, resp *resource.ValidateConfigResponse) {
	var cfg statusPageModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &cfg)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if cfg.Access.ValueString() == "password" && cfg.Password.IsNull() {
		resp.Diagnostics.AddAttributeError(path.Root("password"), "Missing password",
			"A status page with access = \"password\" requires a password.")
	}
}

func (m *statusPageModel) toInput(update bool) client.StatusPageInput {
	in := client.StatusPageInput{
		"name":             m.Name.ValueString(),
		"hosted_subdomain": m.HostedSubdomain.ValueString(),
	}
	for name, v := range map[string]types.String{
		"custom_domain": m.CustomDomain,
		"logo_url":      m.LogoURL,
		"website_url":   m.WebsiteURL,
		"support_url":   m.SupportURL,
		"ip_allowlist":  m.IPAllowlist,
	} {
		if known(v) || update {
			in[name] = nullableString(v)
		}
	}
	if known(m.Password) {
		in["password"] = m.Password.ValueString()
	}
	for name, v := range map[string]types.String{
		"default_time_period": m.DefaultTimePeriod,
		"access":              m.Access,
		"environment":         m.Environment,
	} {
		if known(v) {
			in[name] = v.ValueString()
		}
	}
	for name, v := range map[string]types.Bool{
		"allow_search_index":         m.AllowSearchIndex,
		"enable_performance_metrics": m.EnablePerformanceMetrics,
		"enable_dark_mode":           m.EnableDarkMode,
	} {
		if known(v) {
			in[name] = v.ValueBool()
		}
	}
	return in
}

func (m *statusPageModel) fromAPI(api *client.StatusPage) {
	m.ID = types.StringValue(api.Key)
	m.Key = types.StringValue(api.Key)
	m.Name = types.StringValue(api.Name)
	m.HostedSubdomain = types.StringValue(api.HostedSubdomain)
	m.CustomDomain = stringPtrOrNull(api.CustomDomain)
	m.LogoURL = stringPtrOrNull(api.LogoURL)
	m.WebsiteURL = stringPtrOrNull(api.WebsiteURL)
	m.SupportURL = stringPtrOrNull(api.SupportURL)
	m.AllowSearchIndex = types.BoolValue(api.AllowSearchIndex)
	m.EnablePerformanceMetrics = types.BoolValue(api.EnablePerformanceMetrics)
	m.EnableDarkMode = types.BoolValue(api.EnableDarkMode)
	m.DefaultTimePeriod = stringOrNull(api.DefaultTimePeriod)
	m.Access = stringOrNull(api.Access)
	// password is write-only: keep whatever is in the plan or state.
	m.IPAllowlist = stringOrNull(string(api.IPAllowlist))
	m.Environment = stringOrNull(string(api.Environment))
	m.BadgeURLLight = stringOrNull(api.BadgeURLLight)
	m.BadgeURLDark = stringOrNull(api.BadgeURLDark)
	m.Created = stringOrNull(api.Created)
}

func (r *statusPageResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan statusPageModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	api, err := r.client.CreateStatusPage(ctx, plan.toInput(false))
	if err != nil {
		resp.Diagnostics.AddError("Error creating status page", err.Error())
		return
	}
	plan.fromAPI(api)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *statusPageResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state statusPageModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	api, err := r.client.GetStatusPage(ctx, state.Key.ValueString())
	if client.IsNotFound(err) {
		resp.State.RemoveResource(ctx)
		return
	}
	if err != nil {
		resp.Diagnostics.AddError("Error reading status page", err.Error())
		return
	}
	state.fromAPI(api)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *statusPageResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan statusPageModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	api, err := r.client.UpdateStatusPage(ctx, plan.Key.ValueString(), plan.toInput(true))
	if err != nil {
		resp.Diagnostics.AddError("Error updating status page", err.Error())
		return
	}
	plan.fromAPI(api)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *statusPageResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state statusPageModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.client.DeleteStatusPage(ctx, state.Key.ValueString()); err != nil && !client.IsNotFound(err) {
		resp.Diagnostics.AddError("Error deleting status page", err.Error())
	}
}

func (r *statusPageResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("key"), req, resp)
}
